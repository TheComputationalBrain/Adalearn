"""
This script identifies individual volatility for each participant across all task sessions. An initial guess for the optimiser is first generated by finding the lowest mean squared error value from random samples. This initial guess is then put forward as an initial start point for the optimiser to use. The identified optimal individual volatility values for each participant are stroed in a dataframe and saved as a .csv file. 
"""

import pandas as pd
import sys
import numpy as np
from scipy import stats
import scipy.optimize as so
from pathlib import Path
import plotly.io as pio
import plotly.graph_objects as go
import plotly.express as px
from plotly.subplots import make_subplots
pio.renderers.default='browser'

import adalearn_analysis_group_level_functions_data_utilities as group_data_utils
import adalearn_analysis_participant_level_functions_comp as comp

from adalearn_pupil.adalearn_pupil_participant_info_and_parameters import base_dir, condition_str, P_C, P1_MAX, P1_MIN, RESOL



# Loading data
dataframes = group_data_utils.load_sample_csvs(directory_path=base_dir, substrings=[
    'change_point_indices_df', 
    'computational_var_df'
])

new_inference_data = dataframes['computational_var_df'][['participant', 'task_session', 'outcome', 'estimate']].copy()

# Estimating initial guess of optimal p_c before running optimisation procedure
individual_p_c = []

for participant in new_inference_data['participant'].unique():
    data = new_inference_data[new_inference_data['participant']==participant]

    lb = np.array([0.0001])
    ub = np.array([0.9])
            
    bounds = [(lb, ub)]

    best_mse = np.inf
    fp_init = None

    n_initial_guesses = 100

    print(f'Estimating best initial guess...')
    for ii in range(n_initial_guesses):

        fp_random = lb + (ub - lb) * np.random.rand(len(lb))
        fp_random = np.maximum(np.minimum(fp_random, ub), lb)

        mse = comp.inference_and_mse(pars=fp_random,data=data, p_c=P_C, p1_min=P1_MIN, p1_max=P1_MAX, resol=RESOL)

        if mse < best_mse:
            best_mse = mse
            fp_init = fp_random

    fp_init = np.array(fp_init)
    
    print(f'Running optimsation for participant: {participant} with initial guess: {fp_init}...')
    opt = so.minimize(comp.inference_and_mse, fp_init, args=(data, P_C, P1_MIN, P1_MAX, RESOL),
                                method='Powell', bounds=bounds, options={'disp': False}) 
            
    fval = opt['fun']
    x_min = opt['x']
    result = opt["success"]

    opt_results = pd.DataFrame({
        'participant': participant,
        'optimal_p_c': x_min
    })

    individual_p_c.append(opt_results)
    
individual_p_c_df = pd.concat(individual_p_c, ignore_index=True)

# Save group-level csv
group_data_utils.save_sample_dataframes_to_csv(dataframes={
    'individual_p_c_df': individual_p_c_df
},
directory_path=base_dir,
condition_str=condition_str,
task='Pupil'
)

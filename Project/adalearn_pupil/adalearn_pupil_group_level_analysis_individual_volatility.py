"""
This script identifies individual volatility for each participant performing the Pupil task of the Adalearn project. An initial guess for the optimiser is first generated by finding the lowest mean squared error value from random samples. This initial guess is then put forward as an initial starting point for the optimiser to use. All analysis involving prior confidence and change point probability is then reperformed. The identified optimal individual volatility values, and new uncertainty-associated analyses for each participant are stored in a dataframe and saved as a .csv files. The following scripts need to be run before running this script to obtain the relevant .csv files:
- adalearn_pupil_group_level_participant_demographics.py
- adalearn_pupil/adalearn_pupil_group_level_analysis_behav_task_performance.py
- adalearn_pupil/adalearn_pupil_group_level_analysis_model_parameters.py
- adalearn_pupil/adalearn_pupil_group_level_analysis_learning_rate_analysis.py
- adalearn_pupil/adalearn_pupil_group_level_analysis_pupil_assessment.py
"""
import pandas as pd
import sys
import numpy as np
from scipy import stats
import scipy.optimize as so
from pathlib import Path

parent_dir = Path(__file__).resolve().parent.parent
sys.path.append(str(parent_dir))

import adalearn_analysis_group_level_functions_data_utilities as group_data_utils
import adalearn_analysis_participant_level_functions_comp as comp
import adalearn_analysis_participant_level_functions_regression_pupil as pupil_regress
import adalearn_analysis_group_level_functions_statistical_analysis as group_stats_analysis
import adalearn_analysis_group_level_functions_pupil_analysis as group_pupil

from adalearn_pupil.adalearn_pupil_participant_info_and_parameters import base_dir, condition_str, exclude_zero, P1_MAX, P1_MIN, RESOL



# Loading data
dataframes = group_data_utils.load_sample_csvs(
    directory_path=base_dir,
    substrings=[
        'exclude_participants_behav_cor_df',
        'exclude_participants_pupil_analysis_df', 
        'change_point_indices_df', 
        'computational_var_df', 
        'outcome_epochs_descriptive_stats_df',
        'outcome_epoched_pupil_df',
        'outcome_epochs_columns_df',
        'outcome_epochs_to_remove_df',
        'outcome_epochs_descriptive_stats_nobc_df', 
        'outcome_epoched_pupil_nobc_df'
        ],
    prefix='sample_level_analysis-ses_01-task_Adalearn_Pupil-')

# Setting random seed for reproducibility
np.random.seed(42)

# Loading participant list and excluded participants
participant_list = group_data_utils.get_participant_numbers(directory=Path(f'{base_dir}/data'))

excluded_participants_behav = list(dataframes['exclude_participants_behav_cor_df']['participant'])

excluded_participants_pupil = list(dataframes['exclude_participants_pupil_analysis_df']['exclude_participant'])

# Creating new computatiional variable dataframe for inference
new_inference_data = dataframes['computational_var_df'].copy()

# Creating lists to strore data
individual_p_c = []
comp_df_list = []
group_uncertainty_params_on_lr_list = []
pupil_regress_coef_df_list = []
pupil_regress_coef_nobc_df_list = []

# Estimating initial guess of optimal p_c before running optimisation procedure
for participant in participant_list:
    if participant not in excluded_participants_behav:
        participant_str = str(participant).zfill(2)
        print(f"\n\n\nProcessing participant {participant_str}...")
        directory_path = Path(f'{base_dir}/data/sub-{participant_str}')
    else:
        continue

    # Getting individual participant data
    comp_df = new_inference_data[new_inference_data['participant']==participant].copy()
    comp_df = comp_df.reset_index()

    change_points = dataframes['change_point_indices_df'][dataframes['change_point_indices_df']['participant'] == participant].copy()
    epoch_data = dataframes['outcome_epoched_pupil_df'][dataframes['outcome_epoched_pupil_df']['participant'] == participant]
    epoch_nobc_data = dataframes['outcome_epoched_pupil_nobc_df'][dataframes['outcome_epoched_pupil_nobc_df']['participant'] == participant]
    epoch_descriptive_stats = dataframes['outcome_epochs_descriptive_stats_df'][dataframes['outcome_epochs_descriptive_stats_df']['participant']==participant]
    epoch_nobc_descriptive_stats = dataframes['outcome_epochs_descriptive_stats_nobc_df'][dataframes['outcome_epochs_descriptive_stats_nobc_df']['participant']==participant]
    analysed_epochs = dataframes['outcome_epochs_columns_df'][dataframes['outcome_epochs_columns_df']['participant']==participant]
    epochs_to_remove = dataframes['outcome_epochs_to_remove_df'][dataframes['outcome_epochs_to_remove_df']['participant']==participant]

    # Parameters to define the initial search
    lb = np.array([0.0001])
    ub = np.array([0.9])
            
    bounds = [(lb, ub)]

    best_mse = np.inf
    fp_init = None

    n_initial_guesses = 100

    # Running inference using guesses to identify starting point for optimisation based on mse
    print(f'\nEstimating best initial guess...')
    for ii in range(n_initial_guesses):

        fp_random = lb + (ub - lb) * np.random.rand(len(lb))
        fp_random = np.maximum(np.minimum(fp_random, ub), lb)

        mse = comp.inference_and_mse(pars=fp_random, data=comp_df, p1_min=P1_MIN, p1_max=P1_MAX, resol=RESOL)

        if mse < best_mse:
            best_mse = mse
            fp_init = fp_random

    fp_init = np.array(fp_init)
    
    # Performing optimisation based on guess with lowest mse
    print(f'Running optimsation for participant: {participant} with initial guess: {fp_init}...')
    opt = so.minimize(comp.inference_and_mse, fp_init, args=(comp_df, P1_MIN, P1_MAX, RESOL), method='Powell', bounds=bounds, options={'disp': False}) 
            
    fval = opt['fun']
    x_min = opt['x']
    result = opt["success"]

    opt_results = pd.DataFrame({
        'participant': participant,
        'optimal_p_c': x_min
    })

    individual_p_c.append(opt_results)

    # Running updated analysis with individual volatility (i.e. x_min)
    # Running inference
    print(f'Running inference and extracting uncertainty parameters...')
    comp_df,_ = comp.run_inference_from_observations(participant_str=participant_str, condition_str=condition_str, directory_path=directory_path, computational_var_df=comp_df, change_point_indices_df=change_points, p_c=x_min, p1_min=P1_MIN, p1_max=P1_MAX, resol=RESOL, plot_surprise=False, plot_posterior_conf=False, plot_posterior_dist_means=False)

    # Computing prior confidence and change point probability of each observation
    comp_df = comp.compute_prior_conf_and_cpp_from_observations(participant_str=participant_str, condition_str=condition_str,directory_path=directory_path, computational_var_df=comp_df, change_point_indices_df=change_points, resol=RESOL, p_c=x_min, p1_min=P1_MIN, p1_max=P1_MAX, conf_type='prev-conf', unit='confidence', plot_distribution_mean=False, plot_prior_conf=False, plot_cpp=False)

    # Running uncertainty-associated analysis on learning rate
    (f"Computing the effect of uncertainty parameters on learning rate...")
    # Linear regression for uncertainty parameters on participants' learning rate
    learning_rate_analysis_dict = comp.uncertainty_on_learning_rate_participant_level(participant_str=participant_str, condition_str=condition_str, directory_path=directory_path, computational_var_df=comp_df, n_bins=6, parameter_estimate='estimate', exclude_zero=exclude_zero, include_interaction=True, plot_corr_subplots=False)

    # Linear regression for uncertainty parameters on model learning rate (normative account)
    learning_rate_model_analysis_dict = comp.uncertainty_on_learning_rate_participant_level(participant_str=participant_str, condition_str=condition_str, directory_path=directory_path, computational_var_df=comp_df, n_bins=6, parameter_estimate='ideal_observer', exclude_zero=exclude_zero, include_interaction=True, plot_corr_subplots=False)

    group_uncertainty_params_on_lr = pd.merge(left=learning_rate_analysis_dict['uncertainty_v_lr_df'], right=learning_rate_model_analysis_dict['uncertainty_v_lr_df'], on=['variable'], how='outer', suffixes=('', '_model'))

    group_uncertainty_params_on_lr['participant'] = participant_str

    group_uncertainty_params_on_lr_list.append(group_uncertainty_params_on_lr)

    # Running analysis of the effect of uncertainty parameters on pupil signal
    if participant not in excluded_participants_pupil:
        # Processing epoched dataframes
        column_titles = list(analysed_epochs['columns'].values.astype(int))

        if len(column_titles)+len(epochs_to_remove) == len(comp_df):
            print(f'correct number of epochs imported for participant {participant_str}')
        else:
            print(f'incorrect number of epochs imported for participant {participant_str}')
        epoch_data = epoch_data.drop(columns=['participant'])
        epoch_data = epoch_data.T
        epoch_data.columns = column_titles
        epoch_data['mean'] = epoch_descriptive_stats['mean'].values.astype(float)
        epoch_data['std'] = epoch_descriptive_stats['std'].values.astype(float)
        epoch_data['sem'] = epoch_descriptive_stats['sem'].values.astype(float)
        epoch_data['time'] = epoch_descriptive_stats['time'].values.astype(float)

        epoch_nobc_data = epoch_nobc_data.drop(columns=['participant'])
        epoch_nobc_data = epoch_nobc_data.T
        epoch_nobc_data.columns = column_titles
        epoch_nobc_data['mean'] = epoch_nobc_descriptive_stats['mean'].values.astype(float)
        epoch_nobc_data['std'] = epoch_nobc_descriptive_stats['std'].values.astype(float)
        epoch_nobc_data['sem'] = epoch_nobc_descriptive_stats['sem'].values.astype(float)
        epoch_nobc_data['time'] = epoch_nobc_descriptive_stats['time'].values.astype(float)

        # Running peristimulus regression analysis
        print(f"Running regression on baseline corrected pupil signal...")   
        conf_cpp_coef, pupil_regress_df, residuals_df = pupil_regress.pupil_peristimulus_regression_analysis(participant_str=participant, condition_str=condition_str, directory_path=directory_path, computational_var_df=comp_df, outcome_epoched_pupil_df=epoch_data, outcome_epochs_to_remove=epochs_to_remove, variables=['prior_conf', 'cpp'], covariates = ['outcome', 'outcome_num', 'task_session', 'prior'], baseline_corrected=True,  plot_regression_analysis=False)

        conf_cpp_coef['participant'] = participant
        conf_cpp_coef['count'] = range(len(conf_cpp_coef))

        pupil_regress_coef_df_list.append(conf_cpp_coef)
    
        print(f"\nRunning regression on non-baseline corrected pupil signal...")
        conf_cpp_coef_nobc, pupil_regress_nobc_df, residuals_nobc_df = pupil_regress.pupil_peristimulus_regression_analysis(participant_str=participant, condition_str=condition_str, directory_path=directory_path, computational_var_df=comp_df, outcome_epoched_pupil_df=epoch_nobc_data, outcome_epochs_to_remove=epochs_to_remove, variables=['prior_conf', 'cpp'], covariates = ['outcome', 'outcome_num', 'task_session', 'prior'], baseline_corrected=False,  plot_regression_analysis=False)

        conf_cpp_coef_nobc['participant'] = participant
        conf_cpp_coef_nobc['count'] = range(len(conf_cpp_coef_nobc))

        pupil_regress_coef_nobc_df_list.append(conf_cpp_coef_nobc) 
        comp_df_list.append(comp_df)
    else:
        continue
    
# Concatenating dataframes
ind_vol_comp_df = pd.concat(comp_df_list, ignore_index=True)
individual_p_c_df = pd.concat(individual_p_c, ignore_index=True)
pupil_regress_coef_df = pd.concat(pupil_regress_coef_df_list, ignore_index=True)
pupil_regress_coef_nobc_df = pd.concat(pupil_regress_coef_nobc_df_list, ignore_index=True)
group_uncertainty_params_on_lr_df = pd.concat(group_uncertainty_params_on_lr_list)

# Perform group_level analysis of uncertainty parameters on learning rate
# Collate regression weights and then perform 1-sample and paired-sample t-tests
behav_conf_coef = group_uncertainty_params_on_lr_df[group_uncertainty_params_on_lr_df['variable'] == 'conf_zscore'].sort_values('participant').copy()
behav_cpp_coef = group_uncertainty_params_on_lr_df[group_uncertainty_params_on_lr_df['variable'] == 'cpp_zscore'].sort_values('participant').copy()

behav_conf_coef_mean = behav_conf_coef['coefficient'].mean()
behav_cpp_coef_mean = behav_cpp_coef['coefficient'].mean()
behav_conf_coef_sem = stats.sem(behav_conf_coef['coefficient'])
behav_cpp_coef_sem = stats.sem(behav_cpp_coef['coefficient'])

# t-tests against zero and between coefficients
t_conf = stats.ttest_1samp(behav_conf_coef['coefficient'], 0)
t_cpp = stats.ttest_1samp(behav_cpp_coef['coefficient'], 0)
t_between_coef = stats.ttest_rel(behav_conf_coef['coefficient'], behav_cpp_coef['coefficient'], alternative='two-sided')

uncertainty_params_ttest_df = pd.DataFrame({
    'variable': ['conf_zscore', 'cpp_zscore', 'between_coef'],
    'regression_coef': [behav_conf_coef_mean, behav_cpp_coef_mean, None],
    'regress_coef_sem': [behav_conf_coef_sem, behav_cpp_coef_sem, None],
    't_statistic': [t_conf.statistic, t_cpp.statistic, t_between_coef.statistic],
    'p_value': [t_conf.pvalue, t_cpp.pvalue, t_between_coef.pvalue]
})

# Running cluster permutation analysis on pupil signals
cluster_based_permutation_results, significant_clusters_df = group_stats_analysis.compute_group_level_permutation_cluster_test(group_level_df=pupil_regress_coef_df, vars = ['prior_conf', 'cpp'], alpha=0.05)

cluster_based_permutation_results_nobc, significant_clusters_nobc_df = group_stats_analysis.compute_group_level_permutation_cluster_test(group_level_df=pupil_regress_coef_nobc_df, vars=['prior_conf', 'cpp'], alpha=0.05)

# Creating a dataframe to contain the averaged pupil response across time points within the epoch
print(f'\n Creating dataframe containing the averaged coefficients for the baseline corrected pupil signal')

coefs_df = group_pupil.compute_peristim_mean_sem_by_count(pupil_regress_coef_df, value_cols=['cpp', 'prior_conf'])
coefs_nobc_df = group_pupil.compute_peristim_mean_sem_by_count(pupil_regress_coef_nobc_df, value_cols=['cpp', 'prior_conf'])

# Save group-level csv
group_data_utils.save_sample_dataframes_to_csv(dataframes={
    'individual_p_c_df': individual_p_c_df,
    'ind_vol_comp_df': ind_vol_comp_df,
    'ind_vol_pupil_regress_coef_df': pupil_regress_coef_df,
    'ind_vol_pupil_regress_coef_nobc_df': pupil_regress_coef_nobc_df,
    'ind_vol_coefs_df': coefs_df,
    'ind_vol_coefs_nobc_df': coefs_nobc_df,
    'ind_vol_cluster_permutation_analysis': significant_clusters_df,
    'ind_vol_cluster_permutation_analysis_nobc': significant_clusters_nobc_df,
    'ind_vol_uncertainty_params_on_lr_df': group_uncertainty_params_on_lr_df,
    'ind_vol_uncertainty_params_ttest_df': uncertainty_params_ttest_df
},
directory_path=base_dir,
condition_str=condition_str,
task='Pupil'
)
